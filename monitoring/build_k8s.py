"""Generate k8s/monitoring-config.yaml (ConfigMaps) from the files in monitoring/.

The files in monitoring/ are the single source of truth (docker compose mounts them directly);
Argo CD applies plain YAML, so the ConfigMaps are generated. A test fails when they drift.
Usage: python monitoring/build_k8s.py
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
OUT = ROOT.parent / "k8s" / "monitoring-config.yaml"


class Block(str):
    pass


yaml.add_representer(Block, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def render() -> str:
    def cm(name, files):
        data = {k: Block(Path(ROOT, p).read_text().rstrip("\n") + "\n") for k, p in files.items()}
        return {"apiVersion": "v1", "kind": "ConfigMap",
                "metadata": {"name": name, "namespace": "secureship"}, "data": data}

    docs = [
        cm("prometheus-config", {"prometheus.yml": "prometheus.yml", "rules.yml": "rules.yml"}),
        cm("alertmanager-config", {"alertmanager.yml": "alertmanager.yml"}),
        cm("grafana-config", {"datasource.yml": "grafana/datasource.yml",
                              "dashboards.yml": "grafana/dashboards.yml",
                              "secureship.json": "grafana/dashboards/secureship.json"}),
    ]
    head = "# GENERATED by monitoring/build_k8s.py from monitoring/ - do not edit by hand.\n"
    return head + yaml.dump_all(docs, sort_keys=False, default_flow_style=False, width=1000)


if __name__ == "__main__":
    OUT.write_text(render())
    print("wrote", OUT)
